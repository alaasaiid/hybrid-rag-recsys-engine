import os
import time
import torch
import torch.nn as nn
import onnxruntime as ort
from onnxruntime.quantization import quantize_dynamic, QuantType
from transformers import AutoModel, AutoTokenizer


class TransformerWrapper(nn.Module):
    """Explicitly forwards positional inputs as keyword arguments to avoid Hugging Face parameter collisions during ONNX tracing."""

    def __init__(self, model):
        super().__init__()
        self.model = model

    def forward(self, input_ids, attention_mask):
        outputs = self.model(input_ids=input_ids, attention_mask=attention_mask)
        return outputs.last_hidden_state


def get_model_size_mb(file_path: str) -> float:
    """Calculates total size in MB, including sidecar weight files generated by PyTorch 2.x ONNX exporters."""
    total_bytes = 0
    directory = os.path.dirname(file_path) or "."
    base_name = os.path.basename(file_path)
    for filename in os.listdir(directory):
        if filename.startswith(base_name):
            total_bytes += os.path.getsize(os.path.join(directory, filename))
    return total_bytes / (1024 * 1024)


def export_and_quantize(
    model_id: str = "sentence-transformers/all-MiniLM-L6-v2",
    output_dir: str = "onnx_models",
) -> dict:
    os.makedirs(output_dir, exist_ok=True)
    fp32_path = os.path.join(output_dir, "encoder_fp32.onnx")
    int8_path = os.path.join(output_dir, "encoder_int8.onnx")

    tokenizer = AutoTokenizer.from_pretrained(model_id)
    raw_model = AutoModel.from_pretrained(model_id)
    raw_model.eval()

    wrapped_model = TransformerWrapper(raw_model)
    wrapped_model.eval()
    
    dummy = tokenizer(
        ["hybrid search and onnx quantization benchmark"],
        padding=True,
        truncation=True,
        return_tensors="pt",
    )

    torch.onnx.export(
        wrapped_model,
        (dummy["input_ids"], dummy["attention_mask"]),
        fp32_path,
        input_names=["input_ids", "attention_mask"],
        output_names=["last_hidden_state"],
        dynamic_axes={
            "input_ids": {0: "batch_size", 1: "seq_len"},
            "attention_mask": {0: "batch_size", 1: "seq_len"},
            "last_hidden_state": {0: "batch_size", 1: "seq_len"},
        },
        opset_version=18,
    )

    quantize_dynamic(
        model_input=fp32_path,
        model_output=int8_path,
        weight_type=QuantType.QInt8,
    )

    sess_fp32 = ort.InferenceSession(fp32_path, providers=["CPUExecutionProvider"])
    sess_int8 = ort.InferenceSession(int8_path, providers=["CPUExecutionProvider"])
    ort_inputs = {
        "input_ids": dummy["input_ids"].numpy(),
        "attention_mask": dummy["attention_mask"].numpy(),
    }

    for _ in range(5):
        sess_fp32.run(None, ort_inputs)
        sess_int8.run(None, ort_inputs)

    runs = 50
    t0 = time.perf_counter()
    for _ in range(runs):
        sess_fp32.run(None, ort_inputs)
    fp32_ms = ((time.perf_counter() - t0) / runs) * 1000.0

    t0 = time.perf_counter()
    for _ in range(runs):
        sess_int8.run(None, ort_inputs)
    int8_ms = ((time.perf_counter() - t0) / runs) * 1000.0

    size_fp32 = get_model_size_mb(fp32_path)
    size_int8 = get_model_size_mb(int8_path)

    metrics = {
        "fp32_size_mb": round(size_fp32, 2),
        "int8_size_mb": round(size_int8, 2),
        "size_reduction_pct": round((1 - size_int8 / max(size_fp32, 1e-6)) * 100, 1),
        "fp32_latency_ms": round(fp32_ms, 2),
        "int8_latency_ms": round(int8_ms, 2),
        "speedup_factor": round(fp32_ms / max(int8_ms, 1e-6), 2),
    }
    print(metrics)
    return metrics


if __name__ == "__main__":
    export_and_quantize()